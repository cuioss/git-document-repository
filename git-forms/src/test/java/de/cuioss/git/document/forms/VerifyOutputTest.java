package de.cuioss.git.document.forms;

import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.TreeMap;


import de.cuioss.git.document.testing.LocalRepository;
import org.eclipse.jgit.lib.Repository;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The main class of the check of the generated output (GDR-FORMS-4) through {@link VerifyOutput#run}, against local
 * repositories of {@code git-testing} and without network: exit code {@code 0} when every output matches, {@code 1}
 * with one line per mismatching output path, {@code 2} for a usage error, a missing or refused schema or template file,
 * a file that is a symbolic link or whose parent directory is one, a collection that is no name segment, a directory that is no repository and an unknown revision; nothing printed
 * carries data.
 * <p>
 * The exit codes, the usage line and the printed details are the specified vocabulary and kept as literals; the data
 * are generated by {@link OutputCheckTest.Document}.
 */
@DisplayName("VerifyOutput (GDR-FORMS-4)")
class VerifyOutputTest {

    @TempDir
    Path temp;

    /** What a run printed and returned. */
    private record Ran(int code, String out, String err) {
    }

    private static Ran run(String... args) {
        var out = new ByteArrayOutputStream();
        var err = new ByteArrayOutputStream();
        int code;
        try (var outStream = new PrintStream(out, true, StandardCharsets.UTF_8);
             var errStream = new PrintStream(err, true, StandardCharsets.UTF_8)) {
            code = VerifyOutput.run(args, outStream, errStream);
        }
        return new Ran(code, out.toString(StandardCharsets.UTF_8), err.toString(StandardCharsets.UTF_8));
    }

    /**
     * The real path of the temporary directory: the check refuses a path through a symbolic link, so a temporary root
     * that is itself reached through one must not reach the paths of the tests.
     */
    private Path real() throws IOException {
        return temp.toRealPath();
    }

    private Path file(String name, String content) throws IOException {
        Path file = real().resolve(name);
        Files.writeString(file, content);
        return file;
    }

    /** Creates a symbolic link, {@code false} when the file system refuses to. */
    private static boolean createLink(Path link, Path target) {
        try {
            Files.createSymbolicLink(link, target);
            return true;
        } catch (IOException | UnsupportedOperationException | SecurityException e) {
            return false;
        }
    }

    private Ran runOn(Repository repository, String layout) throws IOException {
        return run(repository.getDirectory().toString(), OutputCheckTest.BRANCH, layout, OutputCheckTest.COLLECTION,
                file("schema.json", SchemaValidatorTest.SCHEMA).toString(),
                file("template.adoc.tpl", OutputCheckTest.TEMPLATE).toString());
    }

    @Test
    @DisplayName("GDR-FORMS-4: exit code 0 when every output matches, nothing printed")
    void matching(@LocalRepository Repository repository) throws Exception {
        var document = OutputCheckTest.Document.generate();
        OutputCheckTest.commit(repository, document.files(document.output()));

        var ran = runOn(repository, VerifyOutput.PER_DOCUMENT);

        assertEquals(new Ran(VerifyOutput.MATCHING, "", ""), ran, "matching");
    }

    @Test
    @DisplayName("GDR-FORMS-4: exit code 1 with one line per mismatching output path, no data")
    void mismatching(@LocalRepository Repository repository) throws Exception {
        var matching = OutputCheckTest.Document.generate();
        var edited = OutputCheckTest.Document.generate();
        var missing = OutputCheckTest.Document.generate();
        Map<String, byte[]> files = new TreeMap<>(matching.files(matching.output()));
        files.putAll(edited.files(edited.output() + "x\n"));
        files.putAll(missing.files(null));
        OutputCheckTest.commit(repository, files);

        var ran = runOn(repository, VerifyOutput.PER_DOCUMENT);

        var expected = new TreeMap<String, String>(Map.of(edited.outputPath(), "", missing.outputPath(), ""));
        assertAll(
                () -> assertEquals(VerifyOutput.MISMATCHING, ran.code(), "mismatching"),
                () -> assertEquals(String.join("\n", expected.keySet()) + "\n", ran.out(), "one line per path"),
                () -> assertEquals("", ran.err(), "no diagnostic"),
                () -> assertFalse(ran.out().contains(edited.title()), "no data"));
    }

    @Test
    @DisplayName("GDR-FORMS-4: a mismatching path that holds a line feed or a backslash is printed on one line")
    void pathOnOneLine(@LocalRepository Repository repository) throws Exception {
        var plain = OutputCheckTest.Document.generate();
        var document = new OutputCheckTest.Document(OutputCheckTest.word() + "\n" + OutputCheckTest.word() + "\\",
                plain.title(), plain.owner(), plain.reason(), plain.summary());
        OutputCheckTest.commit(repository, document.files(null));

        var ran = runOn(repository, VerifyOutput.PER_DOCUMENT);

        String printed = document.outputPath().replace("\\", "\\\\").replace("\n", "\\u000a");
        assertAll(
                () -> assertEquals(VerifyOutput.MISMATCHING, ran.code(), "mismatching"),
                () -> assertEquals(printed + "\n", ran.out(), "one line naming the path, escaped"),
                () -> assertEquals(1, ran.out().lines().count(), "one path, one line"));
    }

    @Test
    @DisplayName("GDR-FORMS-4: data nested too deep once joined is MALFORMED, not a repository that cannot be opened")
    void nestedTooDeep(@LocalRepository Repository repository) throws Exception {
        var document = OutputCheckTest.Document.generate();
        Map<String, byte[]> files = new TreeMap<>(document.files(document.output()));
        files.put(document.directory() + "details.yaml", OutputCheckTest.nestedYaml(DataNode.MAX_DEPTH));
        OutputCheckTest.commit(repository, files);

        var ran = runOn(repository, VerifyOutput.PER_DOCUMENT);

        assertEquals(new Ran(VerifyOutput.FAILED, "",
                        "MALFORMED document.yaml: nested deeper than 128 levels, joined with its parts\n"), ran,
                "the refusal of the join, not NOT_A_REPOSITORY");
    }

    @Test
    @DisplayName("GDR-FORMS-4: a numbered kind is checked by its entries")
    void numbered(@LocalRepository Repository repository) throws Exception {
        var document = OutputCheckTest.Document.generate();
        OutputCheckTest.commit(repository, document.files(document.output()));

        var ran = runOn(repository, VerifyOutput.NUMBERED);

        assertEquals(new Ran(VerifyOutput.MATCHING, "", ""), ran, "the per-document files hold no entry");
    }

    @Test
    @DisplayName("GDR-FORMS-4: exit code 2 for a usage error")
    void usage() {
        var tooFew = run("a", "b");
        var unknownLayout = run("a", "b", "other", "c", "d", "e");

        assertAll(
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", VerifyOutput.USAGE + "\n"), tooFew, "too few"),
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", VerifyOutput.USAGE + "\n"), unknownLayout,
                        "an unknown layout"));
    }

    @Test
    @DisplayName("GDR-FORMS-4: exit code 2 for a missing, refused or symbolically linked file")
    void refusedFiles(@LocalRepository Repository repository) throws Exception {
        var gitDir = repository.getDirectory().toString();
        var schema = file("schema.json", SchemaValidatorTest.SCHEMA).toString();
        var template = file("template.adoc.tpl", OutputCheckTest.TEMPLATE).toString();
        var badTemplate = file("bad.adoc.tpl", "{{#open}}").toString();
        var link = Files.createSymbolicLink(real().resolve("link.json"), Path.of(schema)).toString();
        var missing = real().resolve("missing.json").toString();
        String branch = OutputCheckTest.BRANCH;
        String collection = OutputCheckTest.COLLECTION;

        assertAll(
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", "MALFORMED schema-file: missing file\n"),
                        run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection, missing, template), "missing"),
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", "MALFORMED schema-file: a symbolic link, not read\n"),
                        run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection, link, template), "a link"),
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "",
                                "MALFORMED template-file: line 1: a section that is not closed\n"),
                        run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection, schema, badTemplate), "refused"),
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", "MALFORMED collection: not a name segment\n"),
                        run(gitDir, branch, VerifyOutput.PER_DOCUMENT, ".hidden", schema, template), "collection"),
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", VerifyOutput.INVALID_PATH + "\n"),
                        run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection, "a\0b", template), "no path"));
    }

    @Test
    @DisplayName("GDR-FORMS-4: exit code 2 for a schema or template file whose parent directory is a symbolic link")
    void linkedParentDirectory(@LocalRepository Repository repository) throws Exception {
        var document = OutputCheckTest.Document.generate();
        OutputCheckTest.commit(repository, document.files(document.output()));
        Path directory = Files.createDirectory(real().resolve("configuration"));
        Path schema = Files.writeString(directory.resolve("schema.json"), SchemaValidatorTest.SCHEMA);
        Path template = Files.writeString(directory.resolve("template.adoc.tpl"), OutputCheckTest.TEMPLATE);
        Path linked = real().resolve("cfg");
        assumeTrue(createLink(linked, directory), "the file system creates symbolic links");
        var gitDir = repository.getDirectory().toString();
        String branch = OutputCheckTest.BRANCH;
        String collection = OutputCheckTest.COLLECTION;

        var linkedSchema = run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection,
                linked.resolve("schema.json").toString(), template.toString());
        var linkedTemplate = run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection, schema.toString(),
                linked.resolve("template.adoc.tpl").toString());
        var ordinary = run(gitDir, branch, VerifyOutput.PER_DOCUMENT, collection, schema.toString(),
                template.toString());

        assertAll(
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", "MALFORMED schema-file: a symbolic link, not read\n"),
                        linkedSchema, "a linked parent of the schema file, no path printed"),
                () -> assertEquals(
                        new Ran(VerifyOutput.FAILED, "", "MALFORMED template-file: a symbolic link, not read\n"),
                        linkedTemplate, "a linked parent of the template file, no path printed"),
                () -> assertEquals(new Ran(VerifyOutput.MATCHING, "", ""), ordinary,
                        "the same files in an ordinary directory are read"));
    }

    @Test
    @DisplayName("GDR-FORMS-4: exit code 2 for a directory that is no repository and an unknown revision")
    void repositoryFailures(@LocalRepository Repository repository) throws Exception {
        var schema = file("schema.json", SchemaValidatorTest.SCHEMA).toString();
        var template = file("template.adoc.tpl", OutputCheckTest.TEMPLATE).toString();
        var empty = Files.createDirectory(temp.resolve("empty")).toString();

        var noRepository = run(empty, OutputCheckTest.BRANCH, VerifyOutput.PER_DOCUMENT, OutputCheckTest.COLLECTION,
                schema, template);
        var unknown = run(repository.getDirectory().toString(), "refs/heads/unknown", VerifyOutput.PER_DOCUMENT,
                OutputCheckTest.COLLECTION, schema, template);

        assertAll(
                () -> assertEquals(new Ran(VerifyOutput.FAILED, "", "NOT_A_REPOSITORY git-dir: not a repository\n"),
                        noRepository, "no repository"),
                () -> assertEquals(VerifyOutput.FAILED, unknown.code(), "an unknown revision"),
                () -> assertTrue(unknown.err().startsWith("NOT_FOUND "), "the Git outcome first"));
    }
}

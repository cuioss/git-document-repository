/**
 * The redirect refusal of GDR-CORE-2 end to end (PLAN-02 residual (d)): the JGit 7.8.0 HTTP transport talks to a CUI
 * MockWebServer over HTTPS on the loopback interface, whose answer to the first request
 * ({@code GET .../info/refs?service=git-upload-pack}) is a {@code 302} to the same server under the host
 * {@value #REDIRECT_HOST}, which the policy, admitting {@code https://localhost:<port>} only, refuses. Both the
 * anonymous {@code fetchCommit} on a cache and the {@code fetch} of a named remote end
 * {@link GitOutcome#REFUSED_BY_POLICY} naming the host only, without a second request.
 * <p>
 * The server's certificate is generated by the extension ({@code useHttps = true}); the JGit transport accepts it
 * because the configuration of the test's own repository sets {@code http.sslVerify=false}, which JGit 7.8.0 hands to
 * the {@code GitSession} of the connection factory ({@code TransportHttp} calls
 * {@code HttpConnectionFactory2.newSession()} and {@code GitSession.configure(connection, sslVerify)};
 * {@code JGitRepositoryOperations.PolicyCheckedConnectionFactory.newSession()} delegates to the wrapped
 * {@code JDKHttpConnectionFactory}). No process-wide TLS state is changed and no keystore is committed.
 * <p>
 * The test runs under {@link HermeticGitConfiguration}: the user, system and JGit configuration of the host are empty,
 * so no {@code http.*} setting of the machine that runs the build, URL-specific ones ({@code http.<url>.*}) included,
 * reaches the transport; the repository configuration alone decides the redirect handling.
 */
@HermeticGitConfiguration
@EnableGeneratorController
@EnableTestLogger(rootLevel = TestLogLevel.DEBUG)
@EnableMockWebServer(useHttps = true)
@ModuleDispatcher
@DisplayName("JGitRepositoryOperations refused redirect end to end (GDR-CORE-2)")
class RedirectEndToEndTest {

    /** The host the policy admits: the mock server's own name. */
    private static final String ADMITTED_HOST = "localhost";

    /** The host of the redirect target: the same server on the loopback interface, outside the policy. */
    private static final String REDIRECT_HOST = "127.0.0.1";

    /** JGit 7.8.0's default {@code http.maxRedirects}: positive, so the first redirect reaches the policy guard. */
    private static final int DEFAULT_MAX_REDIRECTS = 5;

    /** The detail of the refused redirect: the host only (GDR-NFR-3). */
    private static final String REFUSED_DETAIL = "redirect to " + REDIRECT_HOST + " is outside the remote policy";

    @TempDir
    Path temp;

    /**
     * Answers every request with a {@code 302} to the same path and query on the same port under
     * {@value #REDIRECT_HOST}.
     *
     * @return the dispatcher of the mock server
     */
    ModuleDispatcherElement getModuleDispatcher() {
        return new ModuleDispatcherElement() {

            @Override
            public String getBaseUrl() {
                return "/";
            }

            @Override
            public Optional<MockResponse> handleGet(RecordedRequest request) {
                var location = "https://" + REDIRECT_HOST + ":" + request.getUrl().port() + request.getTarget();
                return Optional.of(new MockResponse.Builder().code(302).addHeader("Location", location).build());
            }

            @Override
            public Set<HttpMethodMapper> supportedMethods() {
                return Set.of(HttpMethodMapper.GET);
            }
        };
    }

    private static RemotePolicy policy(MockWebServer server) {
        return RemotePolicy.httpsOrigin(URI.create("https://" + ADMITTED_HOST + ":" + server.getPort()));
    }

    private static String repositoryUrl(MockWebServer server) {
        return "https://" + ADMITTED_HOST + ":" + server.getPort() + "/" + TestCommits.name() + ".git";
    }

    /**
     * Trusts the generated certificate for the transports of this repository only, and pins the redirect handling to
     * JGit 7.8.0's defaults ({@code http.followRedirects=initial}, {@code http.maxRedirects=5}) in the repository
     * configuration as well: an {@code http.followRedirects=false} would make {@code TransportHttp} reject the first
     * {@code 302} before the policy guard is reached, and so would an {@code http.maxRedirects=0}, because
     * {@code TransportHttp.redirect} rejects a redirect when the number of redirects so far is not below the limit
     * (JGit 7.8.0 {@code TransportHttp}, {@code HttpConfig}). The host's own settings of the group are hidden by
     * {@link HermeticGitConfiguration}.
     */
    private static void trustGeneratedCertificate(StoredConfig config) throws IOException {
        config.setBoolean(HttpConfig.HTTP, null, HttpConfig.SSL_VERIFY_KEY, false);
        config.setEnum(HttpConfig.HTTP, null, HttpConfig.FOLLOW_REDIRECTS_KEY, HttpConfig.HttpRedirectMode.INITIAL);
        config.setInt(HttpConfig.HTTP, null, HttpConfig.MAX_REDIRECTS_KEY, DEFAULT_MAX_REDIRECTS);
        config.save();
    }

    /** Asserts that exactly the first request reached the server, and that the refused target is loopback. */
    private static void assertOnlyFirstRequest(MockWebServer server) throws Exception {
        assertEquals(1, server.getRequestCount(), "only the first request reaches the server");
        var first = server.takeRequest();
        assertAll(
                () -> assertTrue(first.getTarget().endsWith("/info/refs?service=git-upload-pack"),
                        "the first request is the reference advertisement"),
                () -> assertTrue(InetAddress.getByName(REDIRECT_HOST).isLoopbackAddress(),
                        "the refused redirect target is the loopback interface"));
        LogAsserts.assertSingleLogMessagePresentContaining(TestLogLevel.WARN,
                GitCoreLogMessages.WARN.REMOTE_REFUSED.resolveIdentifierString());
        LogAsserts.assertLogMessagePresentContaining(TestLogLevel.WARN, REDIRECT_HOST);
    }

    @Test
    @DisplayName("GDR-CORE-2: fetchCommit refuses a redirect to a host outside the policy, after one request")
    void fetchCommitRefusesRedirect(MockWebServer server) throws Exception {
        var operations = new JGitRepositoryOperations(RemotePolicy.localOnly());
        var cache = temp.resolve(TestCommits.name() + ".git");
        assertTrue(operations.initCache(cache).isOk(), "the cache repository is initialised");
        try (Repository repository = new FileRepositoryBuilder().setGitDir(cache.toFile()).setMustExist(true)
                     .build()) {
            trustGeneratedCertificate(repository.getConfig());
        }
        var commit = Generators.strings("0123456789abcdef", 40, 40).next();

        var result = operations.fetchCommit(new FetchCommitInput(cache, repositoryUrl(server), commit,
                policy(server)));

        assertEquals(GitResult.of(GitOutcome.REFUSED_BY_POLICY, REFUSED_DETAIL), result,
                "the redirect is refused by its host");
        assertOnlyFirstRequest(server);
    }

    @Test
    @DisplayName("GDR-CORE-2: fetch of a named remote refuses a redirect to a host outside the policy, after one request")
    void fetchRefusesRedirect(MockWebServer server, @LocalRepository Repository client) throws Exception {
        var operations = new JGitRepositoryOperations(policy(server));
        TestCommits.addRemote(client, JGitRepositoryOperations.ORIGIN, repositoryUrl(server));
        trustGeneratedCertificate(client.getConfig());

        var result = operations.fetch(FetchInput.builder().root(client.getDirectory().toPath())
                .remote(JGitRepositoryOperations.ORIGIN).refSpecs(List.of()).build());

        assertEquals(GitResult.of(GitOutcome.REFUSED_BY_POLICY, REFUSED_DETAIL), result,
                "the redirect is refused by its host");
        assertOnlyFirstRequest(server);
    }
}
